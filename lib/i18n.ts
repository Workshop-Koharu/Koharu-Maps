/**
 * Resolves a translated string key with multi-tier fallback:
 * Selected Language -> English -> Korean.
 */
export function getTranslation(lang: string, key: keyof TranslationDictionary): string {
  const currentDict = TRANSLATIONS[lang];
  if (currentDict && currentDict[key]) {
    return currentDict[key]!;
  }
  const enDict = TRANSLATIONS['en'];
  if (enDict && enDict[key]) {
    return enDict[key]!;
  }
  const koDict = TRANSLATIONS['ko'];
  return koDict[key] || String(key);
}

export function getCurrentLanguage(): string {
  if (typeof window === 'undefined') return 'ko';
  return localStorage.getItem('koharu_lang') || 'ko';
}

export function setAppLanguage(langCode: string): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem('koharu_lang', langCode);
  window.dispatchEvent(new CustomEvent('koharu_language_changed', { detail: { lang: langCode } }));
}
